//! 终端方块字符(U+2580..=U+259F:▀ ▄ █ ▌ ░ 及象限块)的矩形表示。
//!
//! 字体里这些字形上下留有缝隙、与行高对不齐,所以改成按格子分数直接画矩形(opencode 的标志与进度条大量使用)。
//!
//! @author ixxxxoooo

/// 一个方块字符:格子内的若干矩形 `(x0, y0, x1, y1)`(0..=1 的分数)与不透明度。
pub struct Block {
    pub rects: &'static [(f32, f32, f32, f32)],
    pub alpha: f32,
}

const UL: (f32, f32, f32, f32) = (0., 0., 0.5, 0.5);
const UR: (f32, f32, f32, f32) = (0.5, 0., 1., 0.5);
const LL: (f32, f32, f32, f32) = (0., 0.5, 0.5, 1.);
const LR: (f32, f32, f32, f32) = (0.5, 0.5, 1., 1.);

/// 方块字符对应的矩形;不是方块字符返回 `None`。
pub fn block(ch: char) -> Option<Block> {
    let b = |rects: &'static [(f32, f32, f32, f32)]| Some(Block { rects, alpha: 1. });
    let shade = |alpha: f32| Some(Block { rects: &[(0., 0., 1., 1.)], alpha });
    match ch {
        '▀' => b(&[(0., 0., 1., 0.5)]),
        '▁' => b(&[(0., 7. / 8., 1., 1.)]),
        '▂' => b(&[(0., 6. / 8., 1., 1.)]),
        '▃' => b(&[(0., 5. / 8., 1., 1.)]),
        '▄' => b(&[(0., 0.5, 1., 1.)]),
        '▅' => b(&[(0., 3. / 8., 1., 1.)]),
        '▆' => b(&[(0., 2. / 8., 1., 1.)]),
        '▇' => b(&[(0., 1. / 8., 1., 1.)]),
        '█' => b(&[(0., 0., 1., 1.)]),
        '▉' => b(&[(0., 0., 7. / 8., 1.)]),
        '▊' => b(&[(0., 0., 6. / 8., 1.)]),
        '▋' => b(&[(0., 0., 5. / 8., 1.)]),
        '▌' => b(&[(0., 0., 0.5, 1.)]),
        '▍' => b(&[(0., 0., 3. / 8., 1.)]),
        '▎' => b(&[(0., 0., 2. / 8., 1.)]),
        '▏' => b(&[(0., 0., 1. / 8., 1.)]),
        '▐' => b(&[(0.5, 0., 1., 1.)]),
        '░' => shade(0.25),
        '▒' => shade(0.5),
        '▓' => shade(0.75),
        '▔' => b(&[(0., 0., 1., 1. / 8.)]),
        '▕' => b(&[(7. / 8., 0., 1., 1.)]),
        '▖' => b(&[LL]),
        '▗' => b(&[LR]),
        '▘' => b(&[UL]),
        '▙' => b(&[UL, LL, LR]),
        '▚' => b(&[UL, LR]),
        '▛' => b(&[UL, UR, LL]),
        '▜' => b(&[UL, UR, LR]),
        '▝' => b(&[UR]),
        '▞' => b(&[UR, LL]),
        '▟' => b(&[UR, LL, LR]),
        _ => None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn 整个区段都有定义_其余不是方块() {
        for c in '\u{2580}'..='\u{259F}' {
            assert!(block(c).is_some(), "{c} 应是方块字符");
        }
        assert!(block('a').is_none());
        assert!(block('─').is_none());
    }

    #[test]
    fn 上半块与阴影() {
        assert_eq!(block('▀').unwrap().rects, &[(0., 0., 1., 0.5)]);
        assert_eq!(block('▒').unwrap().alpha, 0.5);
        assert_eq!(block('█').unwrap().alpha, 1.);
    }
}
